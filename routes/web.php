<?php

declare(strict_types=1);

use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Web Routes
|--------------------------------------------------------------------------
|
| Главная отдаёт полноценную страницу. Страницы категорий продукции
| собираются из config/catalog.php: маршрут отдаёт view готовым массивом
| данных, а Blade выводит карточки циклом. На следующем этапе источник
| данных заменяется на базу — ни маршрут, ни Blade, ни компонент
| ProductCard при этом не меняются.
|
| Страницы товаров (/products/eggs/... и подобные) на этом этапе
| намеренно не создаются, поэтому кнопка «Подробнее» в карточке
| неактивна и не может увести посетителя на 404.
|
| Маршруты категорий создаются циклом по config/site.php. Имя маршрута берётся
| из 'route' того же конфига, поэтому slug в URL, имя маршрута и данные
| страницы всегда согласованы с единственным источником правды. Ссылка на
| неизвестный путь (/products/что-то) не совпадёт ни с одним маршрутом и
| корректно отдаст 404.
|
| Как только появится маршрут с именем из config/site.php, соответствующий
| пункт меню в шапке и подвале автоматически станет ссылкой.
|
*/

Route::view('/', 'site.home')->name('home');

foreach ((array) config('site.products', []) as $slug => $product) {
    Route::view('/products/'.$slug, 'site.products.category', [
        'category' => $slug,
        // Название категории остаётся единым источником правды в config/site.php.
        'product' => $product,
        // Данные страницы категории: intro, hero-изображение, блок каталога.
        'catalog' => (array) config('catalog.'.$slug, []),
        // Финальный CTA общий для обеих категорий.
        'cta' => (array) config('catalog.cta', []),
    ])->name($product['route']);
}
