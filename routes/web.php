<?php

declare(strict_types=1);

use App\Http\Controllers\ProductCategoryController;
use App\Http\Controllers\ProductIndexController;
use App\Http\Controllers\QualityController;
use App\Http\Controllers\SitemapController;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Web Routes
|--------------------------------------------------------------------------
|
| Главная отдаёт полноценную страницу. Страницы категорий продукции
| получают из базы категорию и её активные товары, а оформление и тексты
| берут из config/catalog.php — см. App\Http\Controllers\ProductCategoryController.
|
| Страницы товаров (/products/eggs/... и подобные) на этом этапе намеренно
| не создаются, поэтому кнопка «Подробнее» в карточке не выводится и не
| может увести посетителя на 404.
|
| Имена маршрутов разделов (/products, /about, /quality, /contacts)
| совпадают со значениями 'route' в navigation и footer_navigation
| (config/site.php), поэтому соответствующие пункты шапки и подвала стали
| ссылками сами — правки в разметке не потребовались. Пункты, для которых
| маршрута по-прежнему нет, выводятся неактивными и ведут себя как раньше.
|
| Маршруты «известных» категорий (eggs, chicken) создаются циклом по
| config/site.php: имя маршрута берётся из 'route' того же конфига, и
| ссылка на неизвестный путь (/products/что-то) корректно отдаёт 404.
| Категории, добавленные владельцем в админке, живут по общему маршруту
| products.category (см. ниже), поэтому строка в базе сразу получает
| открывающийся адрес /products/{slug}.
|
| Если категория есть в конфиге, но отсутствует в базе или отключена,
| контроллер отдаёт 404 — адрес остаётся зарегистрированным, чтобы не
| ломать меню в шапке и подвале.
|
| Как только появится маршрут с именем из config/site.php, соответствующий
| пункт меню в шапке и подвале автоматически станет ссылкой.
|
*/

Route::view('/', 'site.home')->name('home');

/*
| Обзорная страница продукции. Список категорий строит контроллер: он
| показывает только те категории из config/site.php, которые активны в базе.
| Адрес /products объявлен до цикла категорий и не пересекается с ним: цикл
| регистрирует адреса вида /products/eggs, они длиннее и не конфликтуют.
*/
Route::get('/products', [ProductIndexController::class, 'index'])->name('products.index');

/*
| Текстовые разделы. Данных из базы им не нужно: заголовки, лиды и
| мета-описания лежат в config/content.php, контакты — в config/site.php.
| Поэтому это обычные представления без контроллера — так же, как главная.
*/
Route::view('/about', 'site.about')->name('about');
/*
| Страница «Качество» собирает тексты из config/content.php и сертификаты из
| базы, поэтому у неё есть контроллер (QualityController), а не Route::view.
| Имя маршрута quality не изменилось, поэтому пункты шапки и подвала
| остались ссылками без правок разметки.
*/
Route::get('/quality', [QualityController::class, 'index'])->name('quality');
Route::view('/contacts', 'site.contacts')->name('contacts');

/*
| Форма обратной связи серверным маршрутом не обрабатывается: заявка
| уходит POST-запросом прямо из браузера в Web3Forms
| (https://api.web3forms.com/submit). Бесплатный тариф Web3Forms принимает
| только запросы с origin браузера, серверные запросы он отклоняет (403),
| поэтому маршрут contacts.store намеренно отсутствует. Форма читает
| access key из config/services.php и несёт его скрытым полем в HTML —
| это идентификатор формы, а не секрет.
*/

/*
| Карта сайта для поисковых систем: /sitemap.xml.
|
| Адрес отдан из маршрута, а не файлом в public/, потому что состав карты
| зависит от данных: постоянные страницы берутся из навигации
| config/site.php, а страницы категорий — из активных категорий в базе.
| Заодно снимается вопрос про домен: адреса собираются из APP_URL, который
| на сервере и так обязан быть настоящим (см. SitemapController).
|
| Файл public/sitemap.xml, если он появится, закроет этот маршрут: статику
| веб-сервер отдаёт раньше приложения. Карта строится маршрутом именно
| поэтому, что её нельзя сделать статической без второго источника правды.
*/
Route::get('/sitemap.xml', [SitemapController::class, 'index'])->name('sitemap');

foreach ((array) config('site.products', []) as $slug => $product) {
    Route::get('/products/'.$slug, [ProductCategoryController::class, 'show'])
        // slug передаётся значением маршрута, а не параметром {…}: так
        // адрес остаётся буквальным и совпадает с ключом config/site.php.
        ->defaults('categorySlug', $slug)
        ->name($product['route']);
}

/*
| Страница категории, добавленной в админке: /products/{categorySlug}.
|
| Маршрут объявлен ПОСЛЕ буквальных адресов известных категорий и сразу же
| дважды страхует конфликт: ограничение на буквы/цифры/дефис не даёт ему
| съесть произвольные пути, а положение в файле гарантирует, что
| /products/eggs и /products/chicken всегда совпадут со своими литералами,
| а не с этим шаблоном.
|
| Неактивная или отсутствующая категория отдаёт 404 в контроллере — так же,
| как «известные» адреса: раздел, отключённый в админке, для посетителя не
| существует.
*/
Route::get('/products/{categorySlug}', [ProductCategoryController::class, 'show'])
    ->where('categorySlug', '[a-z0-9-]+')
    ->name('products.category');
