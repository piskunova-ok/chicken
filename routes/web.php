<?php

declare(strict_types=1);

use App\Http\Controllers\ProductCategoryController;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Web Routes
|--------------------------------------------------------------------------
|
| Главная отдаёт полноценную страницу. Страницы категорий продукции
| получают из базы категорию и её активные товары, а оформление и тексты
| берут из config/catalog.php — см. App\Http\Controllers\ProductCategoryController.
|
| Страницы товаров (/products/eggs/... и подобные) на этом этапе намеренно
| не создаются, поэтому кнопка «Подробнее» в карточке не выводится и не
| может увести посетителя на 404.
|
| Маршруты категорий создаются циклом по config/site.php. Имя маршрута берётся
| из 'route' того же конфига, поэтому slug в URL, имя маршрута и данные
| страницы всегда согласованы с единственным источником правды. Ссылка на
| неизвестный путь (/products/что-то) не совпадёт ни с одним маршрутом и
| корректно отдаст 404 ещё до входа в контроллер.
|
| Если категория есть в конфиге, но отсутствует в базе или отключена,
| контроллер отдаёт 404 — адрес остаётся зарегистрированным, чтобы не
| ломать меню в шапке и подвале.
|
| Как только появится маршрут с именем из config/site.php, соответствующий
| пункт меню в шапке и подвале автоматически станет ссылкой.
|
*/

Route::view('/', 'site.home')->name('home');

foreach ((array) config('site.products', []) as $slug => $product) {
    Route::get('/products/'.$slug, [ProductCategoryController::class, 'show'])
        // slug передаётся значением маршрута, а не параметром {…}: так
        // адрес остаётся буквальным и совпадает с ключом config/site.php.
        ->defaults('categorySlug', $slug)
        ->name($product['route']);
}
