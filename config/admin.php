<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| Доступ к админ-панели
|--------------------------------------------------------------------------
|
| Панель Filament закрыта списком адресов, а не «любым пользователем, кто
| прошёл аутентификацию». Причина простая: в базе есть служебная учётная
| запись из DatabaseSeeder (test@example.com), и при разрешении по умолчанию
| она получила бы права администратора сайта, что никто не планировал.
|
| Список задаётся переменной окружения ADMIN_PANEL_EMAILS — несколько
| адресов через запятую. По умолчанию список пуст, то есть панель закрыта
| для всех, пока администратор явно не перечислит себя.
|
| Это НЕ система ролей и прав: здесь нет ни ролей, ни permissions, ни
| сторонних пакетов для авторизации. Единственное решение — «этот адрес
| входит в список или нет». Полноценная модель прав, если она понадобится,
| будет отдельным решением.
|
| Переменная окружения, а не значение в репозитории: реальные адреса
| администраторов не должны попадать в Git.
|
*/

return [

    /*
    | Адреса, которым открыт вход в панель.
    |
    | Пустая строка разбивается на пустой массив, а не на массив с одним
    | пустым элементом: иначе в список незаметно попадёт «пустой» адрес.
    |
    | @var list<string>
    */
    'panel_access_emails' => array_values(array_filter(
        array_map('trim', explode(',', (string) env('ADMIN_PANEL_EMAILS', ''))),
        static fn (string $email): bool => $email !== '',
    )),

];
