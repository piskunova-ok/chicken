{{--
    СТРАНИЦА КАТЕГОРИИ ПРОДУКЦИИ.

    Общая страница для всех категорий: известных (eggs, chicken — данные
    оформления из config/catalog.php) и добавленных в админке (без таких
    данных — вводный абзац и мета-описание берутся из записи базы).

    Источники данных разделены:
        SQLite + Eloquent -> $category и $products (заголовок h1, хлебные
                             крошки и сетка карточек);
        config/catalog.php -> оформление и тексты страницы (eyebrow, hero,
                             intro, meta_description, заголовок и пометка
                             блока каталога, CTA).

    Разделение временное: заказчиком подтверждены только категории и
    товары, поэтому переносить в базу оформление нельзя — для него ещё
    нет ни колонок, ни данных.

    Структура страницы:
        1. Хлебные крошки
        2. Intro / hero категории: eyebrow, h1, краткое описание, фото
        3. Каталог: h2, лид, пометка, сетка карточек
        4. Небольшой CTA

    Чего здесь сознательно нет: цен, веса, фасовки, типа упаковки, срока
    годности, условий хранения, пищевой ценности и наличия позиций. Эти
    сведения не подтверждены заказчиком, поэтому в базе они NULL, и
    карточки их не выводят. Страница не создаёт впечатления, что сайт
    продаёт, а информирует о разделе, который готовится.

    Название категории для h1 и крошек берётся из базы, а тексты остаются
    в config/catalog.php и config/site.php. Страница товара на этом этапе
    не создаётся, поэтому «Подробнее» в карточках не выводится.
--}}

@php
    use App\Support\Settings;

    /*
     | Хлебные крошки. «Продукция» ведёт на обзорную страницу /products:
     | маршрут products.index создан, поэтому пункт стал ссылкой. До его
     | появления ссылка была бы 404, и элемент выводился текстом.
     |
     | Название последнего элемента — из базы: категория пришла из Eloquent.
     */
    $breadcrumbs = [
        ['label' => 'Главная', 'url' => route('home')],
        ['label' => 'Продукция', 'url' => route('products.index')],
        ['label' => $category->name, 'url' => null],
    ];

    $catalog = $catalog ?? [];
    $catalogBlock = $catalog['catalog'] ?? [];

    /*
     | Есть ли в категории активные товары. Это единственный признак, по
     | которому меняется заголовок блока ассортимента: пока позиции есть,
     | заголовок обещает выбор вариантов и он правдив; когда активных
     | товаров нет, обещание становится ошибкой, и его место занимает
     | сообщение об обновлении ассортимента.
     |
     | Признак общий для всех категорий, а не частный для «Яиц кур»: пустая
     | категория — это состояние любой категории, у которой позиции
     | временно выключены. Тексты лежат в config/content.php, поэтому
     | одна правка меняет поведение везде, а не в одной странице.
     */
    $hasProducts = $products->isNotEmpty();

    /*
     | Заголовок и лид блока. С товарами — прежние значения категории из
     | config/catalog.php, без изменений; без товаров — сообщение из
     | config/content.php, переопределяемое ключами empty_title и
     | empty_text в блоке самой категории.
     |
     | Лид блока при пустом ассортименте не выводится вовсе: он описывает
     | предлагаемые варианты и упаковку, которых на странице нет.
     */
    $catalogHeading = $hasProducts
        ? ($catalogBlock['heading'] ?? 'Ассортимент')
        : ($catalogBlock['empty_title'] ?? config('content.catalog.empty_title', 'Ассортимент'));

    $catalogLead = $hasProducts ? ($catalogBlock['lead'] ?? null) : null;

    $catalogEmptyText = $catalogBlock['empty_text'] ?? config('content.catalog.empty_text');

    /*
     | Мета-описание приходит из конфига, а заголовок собирается из названия
     | категории (из базы) и названия компании: оба значения уже есть в
     | проекте, и дублировать их в catalog.php не нужно.
     |
     | $page — запись категории из config/site.php. Используется только как
     | запасной источник описания: список товаров отсюда больше не читается.
     |
     | Для категории, добавленной в админке, записей в config/catalog.php и
     | config/site.php нет: мета-описание и вводный абзац берутся из колонки
     | description этой же записи базы.
     */
    $pageTitle = $category->name.' — '.Settings::value('company_name');
    $pageDescription = $catalog['meta_description']
        ?? ($page['description'] ?? $category->description ?? null);
@endphp

<x-layouts.app :title="$pageTitle" :description="$pageDescription">
    {{-- ============ ХЛЕБНЫЕ КРОШКИ + INTRO / HERO КАТЕГОРИИ ========= --}}
    {{--
        Крошки и hero живут в одной секции: отдельная секция сразу после
        предыдущей потребовала бы обнулить её верхний отступ, а
        переопределение py-* через pt-0 не работает предсказуемо — при
        равной специфичности побеждает порядок правил в собранном CSS, а не
        порядок классов в атрибуте.

        Геометрия hero та же, что на главной: текст 5/12 слева, фотография
        7/12 справа. Пропорции 16/9 подобраны под исходники категорий
        (768x300 и 764x300 около 2.55:1) — в этом боксе картинка
        растягивается минимально.
    --}}
    <x-section tone="canvas" spacing="default">
        <x-breadcrumbs :items="$breadcrumbs" class="mb-10" />

        <div class="grid gap-10 lg:grid-cols-12 lg:items-center lg:gap-12">
            <div class="lg:col-span-5">
                <x-section-heading
                    :eyebrow="$catalog['eyebrow'] ?? 'Продукция'"
                    :title="$category->name"
                    :lead="$catalog['intro'] ?? $category->description ?? null"
                    level="h1"
                />
            </div>

            <div class="lg:col-span-7">
                {{--
                    asset() обязателен: в конфиге путь хранится относительным —
                    «images/02_eggs.jpg». На главной, где URL равен «/», такой
                    путь случайно работает, но на /products/eggs браузер
                    запросил бы /products/images/… и получил 404. Ссылка
                    должна строиться от корня сайта.
                --}}
                <x-media
                    :src="filled($catalog['image'] ?? null) ? asset($catalog['image']) : null"
                    :alt="$catalog['image_alt'] ?? $category->name"
                    variant="hero"
                    ratio="16/9"
                    priority
                />
            </div>
        </div>
    </x-section>

    {{-- ============================ КАТАЛОГ ========================== --}}
    <x-section tone="surface" spacing="default">
        <x-section-heading
            :title="$catalogHeading"
            :lead="$catalogLead"
        />

        @if (filled($catalogBlock['notice'] ?? null))
            {{--
                Пометка о демонстрационном характере карточек. Она же
                объясняет посетителю, почему у карточек нет характеристик.
            --}}
            <p class="mt-6 max-w-2xl text-body text-ink-muted">
                {{ $catalogBlock['notice'] }}
            </p>
        @endif

        {{--
            Сетка каталога: 1 карточка на мобильном, 2 на планшете, 3 на
            desktop. Одинаковая высота карточек обеспечивается h-full и
            mt-auto у кнопки, поэтому описания и кнопки выравниваются по
            нижнему краю независимо от длины текста.

            $products — активные товары этой категории из базы, уже в
            порядке sort_order, а массив товаров из config/catalog.php
            страница больше не читает.

            Сетка выводится только когда есть что в ней показать. Раньше
            <ul> рендерился всегда, и при нуле активных товаров на странице
            оставалось пустое место после заголовка, обещающего выбор
            вариантов.
        --}}
        @if ($hasProducts)
            <ul class="mt-10 grid gap-6 sm:grid-cols-2 lg:grid-cols-3">
                @foreach ($products as $product)
                    <li class="flex">
                        {{--
                            Адрес фотографии вычисляет модель: Product::imageUrl().
                            Там живут оба типа путей, которые сейчас есть в
                            базе — «images/products/<файл>.jpg» внутри public/
                            (новый, Git) и «products/<ulid>.<ext>» на диске
                            storage (старый, из загрузок админки). Разбирать вид
                            пути в шаблоне нельзя: это знание о колонке image,
                            и принадлежит оно модели.

                            Раньше здесь стоял Storage::disk('public')->url()
                            безусловно — он работал только для старых путей и
                            превращал новые в /storage/… с несуществующим
                            файлом.

                            Характеристики приходят из cardSpecs() модели:
                            сейчас все значения NULL, и компонент не выводит
                            ни одной строки. Подтверждённые значения появятся
                            сами.

                            image-alt не передаётся: в таблице products такой
                            колонки нет, а подставлять выдуманный alt значило
                            бы описать несуществующую фотографию.

                            details-url не передаётся: страниц отдельных товаров
                            ещё нет, поэтому кнопка «Подробнее» не выводится
                            и ссылка на 404 невозможна.
                        --}}
                        <x-product-card
                            class="w-full"
                            :name="$product->name"
                            :image="$product->imageUrl()"
                            :short-description="$product->short_description"
                            :specs="$product->cardSpecs()"
                            :additional-info="$product->additional_info"
                        />
                    </li>
                @endforeach
            </ul>
        @else
            {{--
                Активная категория без активных товаров. Не 404: раздел
                существует и открыт, ассортимент в нём просто пока не
                выведен. Не «нет в наличии»: фактическое наличие продукции
                проекту неизвестно, и такое утверждение было бы выдумкой о
                поставках.

                Оформление повторяет карточку товара — те же скругление,
                рамка и подложка, — поэтому пустое место читается как
                содержимое раздела, а не как дыра в вёрстке.
            --}}
            <div
                class="mt-10 rounded-card border border-line bg-canvas p-6 shadow-soft sm:p-8"
                data-catalog-empty
            >
                <p class="max-w-2xl text-body text-ink-muted">{{ $catalogEmptyText }}</p>
            </div>
        @endif

    </x-section>

    {{-- ============================== CTA ============================ --}}
    {{--
        Кнопка ведёт на route('contacts'), которого ещё нет: x-route-button
        в этом случае выводит неактивное состояние. Ссылка на 404 не
        создаётся.
    --}}
    <x-section tone="canvas" spacing="default">
        <div class="mx-auto max-w-3xl text-center">
            <x-section-heading
                :title="$cta['title'] ?? 'Не нашли нужную информацию?'"
                :lead="$cta['text'] ?? null"
                align="center"
            />

            <div class="mt-8 flex justify-center">
                <x-route-button
                    :label="$cta['button'] ?? 'Связаться с нами'"
                    :route="$cta['route'] ?? 'contacts'"
                />
            </div>
        </div>
    </x-section>
</x-layouts.app>
