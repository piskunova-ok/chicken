<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use App\Models\ProductCategory;
use App\Support\SiteLinks;
use Illuminate\Contracts\View\View;

/**
 * Контроллер страницы «Продукция» — /products.
 *
 * ГРАНИЦА ОТВЕТСТВЕННОСТИ
 *
 * Какие категории существуют — решает база, как и на страницах категорий:
 * неактивная категория для посетителя не существует. Какие именно
 * категории уместно показывать и как они выглядят — конфиг
 * config/site.php, потому что там уже лежат название, описание, подпись
 * к фотографии, подпись кнопки и имя маршрута.
 *
 * Пересечение двух источников сделано явно: страница показывает запись из
 * config/site.php, только если такая активная категория есть в базе. Так
 * администратор может отключить категорию, и она исчезнет с обзорной
 * страницы, не ломая при этом ни одной ссылки: маршрут /products/{slug}
 * остаётся зарегистрированным, а страница категории сама отдаёт 404.
 * И наоборот: категория, добавленная в база без записи в конфиге, на
 * /products не появится — её нечем будет нарисовать, и молчаливый третий
 * пункт в списке был бы выдумкой интерфейса.
 *
 * Здесь нет ничего, кроме одного запроса и одной сборки массива. Отдельный
 * сервис поверх этого означал бы класс ради склейки: при появлении третьего
 * источника (например, страниц отдельных товаров) выносить имеет смысл.
 */
final class ProductIndexController extends Controller
{
    /**
     * Обзорная страница продукции со списком категорий.
     */
    public function index(): View
    {
        /*
         * Активные категории одним запросом, в порядке sort_order. Порядок
         * двухчастный по той же причине, что и на странице категории: id
         * стабилизирует выдачу, когда у нескольких категорий совпал
         * sort_order.
         */
        $activeSlugs = ProductCategory::query()
            ->where('is_active', true)
            ->orderBy('sort_order')
            ->orderBy('id')
            ->pluck('slug')
            ->all();

        /*
         * Ссылку на категорию разрешает SiteLinks: если маршрут когда-нибудь
         * исчезнет из routes/web.php, карточка останется, но без ссылки —
         * вместо ссылки в 404.
         */
        $categories = [];

        foreach ((array) config('site.products', []) as $slug => $product) {
            if (! in_array($slug, $activeSlugs, true)) {
                continue;
            }

            $categories[] = $product + [
                'slug' => $slug,
                'url' => SiteLinks::resolveOne([
                    'label' => $product['name'],
                    'route' => $product['route'],
                ])['url'],
            ];
        }

        return view('site.products.index', [
            'categories' => $categories,
        ]);
    }
}
