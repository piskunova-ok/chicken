<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use App\Http\Requests\StoreContactRequest;
use Illuminate\Http\RedirectResponse;

/**
 * Приём публичной формы обратной связи.
 *
 * ЧТО ДЕЛАЕТ ЭТОТ КОНТРОЛЛЕР СЕЙЧАС
 *
 * Только одно: проверяет форму и возвращает посетителя на /contacts с
 * нейтральным сообщением. Данные проверяются (StoreContactRequest),
 * отбрасываются и больше нигде не остаются.
 *
 * ПОЧЕМУ ТАК, А НЕ ОТПРАВКА
 *
 * Настоящего канала связи у проекта нет: адрес получателя заказчиком не
 * передан, почтовый сервер не настроен, согласованного текста письма нет.
 * Отправлять «в никуда» или писать в лог персональные данные посетителей
 * нельзя, поэтому на этом этапе контроллер ничего не отправляет и ничего
 * не сохраняет. Это осознанная промежуточная точка, а не заглушка, которая
 * притворяется отправкой: сообщение на странице прямо говорит посетителю,
 * что отправка появится позже.
 *
 * ПОЧЕМУ ЛОВУШКА ПРОВЕРЯЕТСЯ ИМЕННО ЗДЕСЬ
 *
 * Сработавшая ловушка выглядит для посетителя ровно так же, как успешная
 * отправка: тот же редирект и то же сообщение. Различать их по ответу
 * нельзя, иначе бот поймёт, что его отсеяли. Проверка стоит здесь, рядом
 * с местом, где появится реальная отправка, чтобы её нельзя было
 * подключить в обход ловушки.
 *
 * @see StoreContactRequest
 */
final class ContactMessageController extends Controller
{
    /**
     * Обработать отправку формы.
     *
     * Проверка полей уже выполнена: если форма заполнена неверно, до
     * метода управление не дойдёт, и Laravel сам вернёт посетителя на
     * /contacts с ошибками и введёнными значениями.
     */
    public function store(StoreContactRequest $request): RedirectResponse
    {
        if (! $request->honeypotIsFilled()) {
            $this->deliver();
        }

        return redirect()
            ->route('contacts')
            ->with(StoreContactRequest::STATUS_KEY, (string) config('content.contact_form.flash'));
    }

    /**
     * Место, где появится настоящая отправка.
     *
     * Пока метод пуст намеренно. Он существует уже сейчас по двум
     * причинам: точка подключения видна в коде, и ловушка для ботов уже
     * прикрывает именно этот вызов, а не абстрактное намерение что-то
     * отправить. Подключить письмо, уведомление или запись в базу здесь
     * можно будет, не пересматривая защиту от спама: метод начнёт принимать
     * StoreContactRequest в тот же момент, когда появится что отправлять.
     */
    private function deliver(): void
    {
        // Намеренно пусто: канала связи ещё нет.
    }
}
