<?php

declare(strict_types=1);

namespace App\Http\Controllers;

use App\Models\ProductCategory;
use Illuminate\Contracts\View\View;

/**
 * Страница категории продукции: /products/{slug}.
 *
 * КОНТРОЛЛЕР, А НЕ ЗАКРЫТИЕ В МАРШРУТЕ
 *
 * Логика страницы перестала помещаться в строку маршрута: нужно найти
 * категорию в базе, отклонить запрос при её отсутствии, отобрать активные
 * товары и задать им порядок. Всё это — решение «что показывать
 * посетителю», а не «какой шаблон отдать», поэтому оно живёт здесь, а
 * routes/web.php остаётся списком адресов и имён маршрутов.
 *
 * Отдельные repository/service-слои для этого не заводились: на этой
 * странице всего два запроса и одно правило отбора, и выносить их в
 * дополнительные классы означало бы прятать тривиальный код за лишним
 * слоем. Если правило отбора понадобится ещё где-то — его вынесу.
 *
 * ГРАНИЦА ОТВЕТСТВЕННОСТИ
 *
 * Из базы берутся только категория, список товаров, их порядок и
 * активность. Оформление страницы (SEO, hero, intro, заголовки, пометка,
 * CTA) приходит из config/catalog.php:
 *
 *  - у известных категорий (eggs, chicken) там лежит готовое оформление;
 *  - у категорий из админки записей в конфиге нет, и страница обходится
 *    запасными значениями: вводный абзац и мета-описание берутся из
 *    колонки description записи базы (см. category.blade.php).
 *
 * Один и тот же контроллер обслуживает и буквальные адреса известных
 * категорий, и общий маршрут products.category: отличие только в источнике
 * оформления, а логика отбора категории и товаров одна и та же.
 */
final class ProductCategoryController extends Controller
{
    /**
     * Показ страницы одной категории.
     *
     * @param  string  $categorySlug  slug из адреса, заданный маршрутом
     *                                из config/site.php.
     */
    public function show(string $categorySlug): View
    {
        /*
         * Категория ищется по slug и по признаку активности ОДНИМ запросом.
         * Неактивная категория для посетителя не существует, поэтому её
         * нельзя отличить от отсутствующей — обе ситуации дают 404.
         *
         * Отбор делает база, а не PHP: Product::all() с последующей
         * фильтрацией в памяти означал бы запрос всего каталога на каждую
         * страницу и полагался бы на то, что в базу не попадёт лишнее.
         */
        $category = ProductCategory::query()
            ->where('slug', $categorySlug)
            ->where('is_active', true)
            ->first();

        /*
         * 404 вместо пустой страницы: без категории нельзя построить ни
         * h1, ни хлебные крошки. Подставлять вместо неё данные из
         * config/catalog.php нельзя — это создало бы вторую правду о том,
         * какие категории существуют, и страница изображала бы раздел,
         * которого на самом деле нет.
         */
        abort_if($category === null, 404);

        /*
         * Товары берутся через отношение категории, поэтому условие
         * product_category_id в запрос не попадает дважды: его уже
         * подставило отношение hasMany.
         *
         * Порядок двухчастный: sort_order задаёт задуманный порядок
         * позиций, а id стабилизирует выдачу, когда у нескольких товаров
         * sort_order совпадает (например, после ручной правки). Без
         * второго ключа база вправе вернуть такие позиции в любом порядке,
         * и страница между двумя одинаковыми запросами выглядела бы по-
         * разному.
         *
         * Eager loading здесь не нужен: родитель один, и его товары
         * загружаются ровно одним запросом. with() дал бы тот же
         * результат в том же числе запросов, а шаблон не обращается к
         * $product->category, поэтому N+1 не возникает. Количество
         * запросов зафиксировано тестом.
         */
        $products = $category->products()
            ->where('is_active', true)
            ->orderBy('sort_order')
            ->orderBy('id')
            ->get();

        return view('site.products.category', [
            // Категория из базы: её название формирует h1 и хлебные крошки.
            'category' => $category,

            // Активные товары этой категории в заданном порядке.
            'products' => $products,

            // Запись категории из config/site.php — источник запасного
            // описания страницы. Сами данные о товарах здесь больше
            // не хранятся и на страницу не влияют.
            'page' => (array) config('site.products.'.$categorySlug, []),

            // Оформление и контент страницы: eyebrow, hero, intro,
            // meta_description, заголовок и пометка блока каталога.
            'catalog' => (array) config('catalog.'.$categorySlug, []),

            // Финальный CTA общий для обеих категорий.
            'cta' => (array) config('catalog.cta', []),
        ]);
    }
}
