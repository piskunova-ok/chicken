<?php

declare(strict_types=1);

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;

/**
 * Проверка публичной формы обратной связи (/contacts).
 *
 * ПОЧЕМУ ОТДЕЛЬНЫЙ FORM REQUEST, А НЕ rules() В КОНТРОЛЛЕРЕ
 *
 * У формы есть поведение, которого нет у обычной проверки: скрытая
 * ловушка для ботов. Она описана в HONEYPOT и обрабатывается в
 * validateResolved() — то есть ДО того, как правила вообще начнут
 * смотреть на запрос. Смысл такой последовательности в том, что бот
 * получает ровно тот же ответ, что и человек с заполненной формой, и по
 * ответу не может понять, что его отсеяла ловушка, а не проверка полей.
 * Если бы ловушка была обычным правилом, бот получил бы ошибки валидации
 * и сразу понял бы, какие поля считаются настоящими.
 *
 * ЧТО ЭТОТ КЛАСС НЕ ДЕЛАЕТ
 *
 * Ничего не сохраняет и не отправляет. Проверенные данные уходят
 * письмом в контроллере, а не здесь: класс отвечает только за то, чтобы
 * до отправки дошли корректные поля. Письмо, его получатель и поведение
 * при сбое описаны в App\Http\Controllers\ContactMessageController —
 * здесь для них нет ни адреса получателя, ни лишних зависимостей.
 *
 * ПОЧЕМУ ПРЕДЕЛЫ ДЛИНЫ ЗДЕСЬ, А НЕ В ШАБЛОНЕ
 *
 * Числа в правилах и числа в атрибутах maxlength должны совпадать, иначе
 * посетитель упрётся в браузерное ограничение раньше, чем в серверное, и
 * получит ошибку, которую невозможно объяснить. Поэтому лимиты объявлены
 * один раз здесь, а шаблон читает их через limitFor().
 *
 * Кто обрабатывает прошедший проверкой запрос — App\Http\Controllers\
 * ContactMessageController. Обратная ссылка намеренно дана текстом, а не
 * тегом @see с полным именем: импорт контроллера в класс запроса ради
 * одного упоминания в документации связал бы их сильнее, чем нужно.
 */
final class StoreContactRequest extends FormRequest
{
    /**
     * Имя скрытой ловушки.
     *
     * Название выбрано нейтральным и правдоподобным для автозаполнения:
     * бот, который обходит формы «по всем текстовым полям», заполнит его
     * охотнее, чем поле с подозрительным именем вроде honeypot.
     */
    public const HONEYPOT = 'website';

    /**
     * Ключ сессионного сообщения о результате обработки.
     *
     * Именованный, а не просто status: страница показывает эту строку в
     * единственном месте, и случайный посторонний flash не должен был бы
     * подставиться под неё.
     */
    public const STATUS_KEY = 'contact_form_status';

    /**
     * Ключ сессионного сообщения о неудачной отправке.
     *
     * Отдельный ключ, а не тот же STATUS_KEY с признаком ошибки: успех и
     * сбой взаимоисключающи, а смешав их, пришлось бы хранить и текст, и
     * тип сообщения. Два именованных ключа делают ветвление в контроллере
     * очевидным, а вывод в шаблоне — независимым: у ошибки свой блок, своя
     * роль для программ доступности и свои цвета.
     */
    public const ERROR_KEY = 'contact_form_error';

    /**
     * Предел длины поля или null, если предел не задан.
     *
     * Единственный источник правды о длине: и rules(), и разметка формы
     * берут числа отсюда.
     */
    public static function limitFor(string $field): ?int
    {
        return match ($field) {
            'name' => 100,
            'phone' => 50,
            'email' => 255,
            'message' => 2000,
            default => null,
        };
    }

    /**
     * Заполнена ли ловушка.
     *
     * Проверка одинакова для всех типов значения: бот может прислать не
     * строку, а массив website[]=..., и такой запрос тоже обязан считаться
     * сработавшей ловушкой, а не молча пройти валидацию.
     */
    public function honeypotIsFilled(): bool
    {
        return filled($this->input(self::HONEYPOT));
    }

    /**
     * Форма публичная: никакой авторизации на отправку не требуется.
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * Правила проверки полей формы.
     *
     * Состав полей намеренно узкий: имя, телефон, необязательная почта,
     * текст сообщения и согласие. Коммерческие поля (компания, ИНН,
     * должность, объём заказа, категория клиента, цена) не добавлены —
     * заказчик их не запрашивал, и форма не должна выглядеть как анкета
     * с придуманными требованиями.
     */
    public function rules(): array
    {
        return [
            'name' => ['required', 'string', 'max:'.self::limitFor('name')],
            'phone' => ['required', 'string', 'max:'.self::limitFor('phone')],
            'email' => ['nullable', 'email', 'max:'.self::limitFor('email')],
            'message' => ['required', 'string', 'max:'.self::limitFor('message')],
            'consent' => ['accepted'],
        ];
    }

    /**
     * Пропустить валидацию, если сработала ловушка.
     *
     * Переопределяется штатный метод FormRequest, который вызывается до
     * входа в контроллер. Возвращаемся молча: никаких ошибок, никакого
     * текста про ловушку — ответ должен быть неотличим от успешной
     * отправки человеком.
     */
    public function validateResolved(): void
    {
        if ($this->honeypotIsFilled()) {
            return;
        }

        parent::validateResolved();
    }
}
