<?php

declare(strict_types=1);

namespace App\Filament\Resources\ProductCategories\Schemas;

use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Schema;

/**
 * Форма категории продукции (создание и редактирование).
 *
 * ПОЛЯ РОВНО ТЕ, ЧТО ЕСТЬ В ТАБЛИЦЕ product_categories
 *
 * Форма содержит все колонки таблицы и ничего кроме них: id, created_at и
 * updated_at — служебные, а выдумывать поля, которых в схеме нет, нельзя.
 * name, slug, is_active и sort_order были и раньше; description — текст для
 * карточки на /products и вводного абзаца страницы категории.
 *
 * ОПИСАНИЕ (description)
 *
 * Пустое значение допустимо: карточка категории на /products и страница
 * /products/{slug} обходятся без вводного текста. Для известных категорий
 * eggs/chicken описание продолжает читаться из config/site.php, для новых
 * категорий — из этой колонки.
 *
 * SLUG: ЗАДАЁТСЯ ПРИ СОЗДАНИИ, НЕ МЕНЯЕТСЯ ПРИ ПРАВКЕ
 *
 * slug — это не данные о разделе, а ключ, по которому публичная часть
 * находит свою страницу: он входит в адрес /products/{slug}. Пока раздел
 * существует, его slug неизменен, иначе старый адрес тихо ушёл бы в 404.
 *
 * Поэтому поведение поля зависит от операции:
 *
 *  - создание: slug вводит администратор (адрес ещё никто не знает, и
 *    ключей в конфиге для новой категории нет — страница живёт по общей
 *    категорийной разметке);
 *  - редактирование: поле видно и заполнено, но dehydrated(false) убирает
 *    его из отправляемых данных целиком — запись обновляет только name,
 *    description, is_active и sort_order. Защита держится на механизме, а
 *    не на disabled() (см. ниже).
 *
 * Почему нельзя доверить одному disabled(): disabled() запрещает ввод, но
 * не запрещает сохранение — значение продолжает участвовать в
 * дегидратации. dehydrated(false) на этапе edit исключает slug до отправки.
 *
 * Уникальность slug проверяется только при создании (ignoreRecord: true):
 * на правке поле не дегидрируется и потому не проходит валидацию.
 */
class ProductCategoryForm
{
    /**
     * Сообщения правил, специфичных для формы категории.
     *
     * @return array<string, string>
     */
    private static function validationMessages(): array
    {
        return [
            'unique' => 'Категория с таким адресом уже существует.',
            'regex' => 'Адрес может содержать только строчные латинские буквы, цифры и дефис.',
        ];
    }

    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                TextInput::make('name')
                    ->label('Название')
                    ->required()
                    // 255 — длина string-колонки из миграции. Ограничение
                    // взято из схемы БД, а не выбрано «на глаз»: в SQLite
                    // длина строки не проверяется, и без правила слишком
                    // длинное название молча обрезалось бы в других СУБД.
                    ->maxLength(255),

                Textarea::make('description')
                    ->label('Описание')
                    ->rows(3)
                    ->columnSpanFull()
                    ->helperText('Показывается в карточке категории на странице «Продукция» и как вводный текст страницы категории. Пустое — карточка обойдётся без описания.'),

                TextInput::make('slug')
                    ->label('Slug')
                    ->required()
                    ->maxLength(255)
                    // Только при создании: см. шапку класса.
                    ->dehydrated(fn (string $operation): bool => $operation === 'create')
                    ->unique(ignoreRecord: true)
                    ->regex('/^[a-z0-9-]+$/')
                    ->validationMessages(self::validationMessages())
                    ->helperText('Адрес категории: /products/{slug}. Задаётся при создании, при правке не изменяется.'),

                Toggle::make('is_active')
                    ->label('Активна')
                    // Предупреждение не про то, что так нельзя, а про то,
                    // что произойдёт: выключенная категория перестаёт
                    // открываться на сайте с 404. Администратор должен
                    // понимать это до нажатия, а не после.
                    ->helperText('Пока категория активна, страница /products/{slug} отдаётся посетителю. Выключенная категория отдаёт 404 — это ожидаемое поведение.'),

                TextInput::make('sort_order')
                    ->label('Порядок')
                    ->required()
                    ->integer()
                    // Колонка объявлена unsignedInteger, поэтому отрицательное
                    // значение не имеет смысла и отсекается формой, а не
                    // ошибкой базы. Ноль допустим: так объявлено значение по
                    // умолчанию в миграции.
                    ->minValue(0)
                    ->helperText('Меньшие значения выводятся раньше.'),
            ]);
    }
}
