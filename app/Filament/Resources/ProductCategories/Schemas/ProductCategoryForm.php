<?php

declare(strict_types=1);

namespace App\Filament\Resources\ProductCategories\Schemas;

use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Schema;

/**
 * Форма редактирования категории продукции.
 *
 * ПОЛЯ РОВНО ЧЕТЫРЕ
 *
 * Форма содержит все колонки таблицы product_categories и ничего кроме
 * них: id, created_at и updated_at — служебные, а выдумывать поля, которых
 * в схеме нет, нельзя (см. шапку миграции).
 *
 * ПОЧЕМУ НЕТ ПОЛЯ SLUG ДЛЯ ПРАВКИ
 *
 * slug — не данные о разделе, а ключ, по которому публичная часть находит
 * свою страницу: он входит в адрес /products/{slug} и в ключ
 * config/catalog.php, откуда берутся eyebrow, hero, intro и заголовок
 * каталога. Смена slug в админке тихо оставила бы старый адрес в 404, а
 * новый — без оформления: ключа с таким значением в конфиге не
 * существует. Обратного пути автоматически не появится, поэтому менять
 * slug через панель нельзя. Когда такая задача понадобится, это будет
 * отдельное решение с переносом настроек страниц в базу, а не ещё одно
 * поле в форме.
 *
 * ПОЧЕМУ НЕЛЬЗЯ ДОВЕРИТЬ ОДНОМУ DISABLED()
 *
 * disabled() запрещает ввод, но не запрещает сохранение: значение поля
 * продолжает участвовать в дегидратации формы, то есть отправляется при
 * сохранении. Само по себе это не испортило бы slug — в форме редактирования
 * поле заполнено из записи, — но полагаться на «заполнено и не изменилось»
 * означало бы, что защита держится на соглашении, а не на механизме.
 * dehydrated(false) убирает slug из отправляемых данных целиком: что бы
 * ни лежало в форме, запись обновляет только name, is_active и sort_order.
 * Поле при этом остаётся видимым и заполненным, то есть администратор
 * видит, по какому адресу живёт категория.
 */
class ProductCategoryForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->components([
                TextInput::make('name')
                    ->label('Название')
                    ->required()
                    // 255 — длина string-колонки из миграции. Ограничение
                    // взято из схемы БД, а не выбрано «на глаз»: в SQLite
                    // длина строки не проверяется, и без правила слишком
                    // длинное название молча обрезалось бы в других СУБД.
                    ->maxLength(255),

                TextInput::make('slug')
                    ->label('Slug')
                    ->disabled()
                    ->dehydrated(false)
                    ->helperText('Задан в базе и используется в публичных адресах /products/{slug} и в config/catalog.php. На этом этапе не изменяется.'),

                Toggle::make('is_active')
                    ->label('Активна')
                    // Предупреждение не про то, что так нельзя, а про то,
                    // что произойдёт: выключенная категория перестаёт
                    // открываться на сайте с 404. Администратор должен
                    // понимать это до нажатия, а не после.
                    ->helperText('Пока категория активна, страница /products/{slug} отдаётся посетителю. Выключенная категория отдаёт 404 — это ожидаемое поведение.'),

                TextInput::make('sort_order')
                    ->label('Порядок')
                    ->required()
                    ->integer()
                    // Колонка объявлена unsignedInteger, поэтому отрицательное
                    // значение не имеет смысла и отсекается формой, а не
                    // ошибкой базы. Ноль допустим: так объявлено значение по
                    // умолчанию в миграции.
                    ->minValue(0)
                    ->helperText('Меньшие значения выводятся раньше.'),
            ]);
    }
}
